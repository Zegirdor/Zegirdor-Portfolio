CREATE TABLE IF NOT EXISTS Repository (
    ID BigInt GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name JSONB NOT NULL DEFAULT '{}'::JSONB CHECK (JSONB_TypeOf(Name) = 'object'),
    Description JSONB NOT NULL DEFAULT '{}'::JSONB CHECK (JSONB_TypeOf(Description) = 'object'),
    Git_Repository_URL Text NOT NULL CHECK (BTrim(Git_Repository_URL) <> ''),
    Demo_URL Text CHECK (Demo_URL IS NULL OR BTrim(Demo_URL) <> ''),
    Screenshot_Path Text,
    Version Text,
    Project_Date Date,
    Authors Text[] NOT NULL DEFAULT ARRAY[]::Text[],
    Completion_Percent SmallInt CHECK (Completion_Percent BETWEEN 0 AND 100),
    Is_Visible Boolean NOT NULL DEFAULT false,
    Display_Order integer NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    Created_At timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT Repository_Unique_URL UNIQUE (Git_Repository_URL),
	CONSTRAINT Webpage_Unique_URL UNIQUE (Demo_URL)
);

CREATE TABLE IF NOT EXISTS Technology (
    ID BigInt GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name Text NOT NULL UNIQUE CHECK (BTrim(Name) <> ''),
    Category Text NOT NULL DEFAULT 'other'
        CHECK (Category IN (
            'language',
            'framework',
            'library',
            'database',
            'tool',
            'other'
        )),
	Proficiency Text NOT NULL DEFAULT 'average'
        CHECK (Proficiency IN (
            'proficient',
            'very high',
            'high',
            'average',
            'low',
            'basic'
        ))
);

CREATE TABLE IF NOT EXISTS Repository_Technology (
    Repository_ID BigInt NOT NULL REFERENCES Repository(ID) ON DELETE CASCADE,
    Technology_ID BigInt NOT NULL REFERENCES Technology(ID),
    PRIMARY KEY (repository_id, technology_id)
);

CREATE INDEX IF NOT EXISTS Repository_Visible_Order_IDX
    ON Repository (Display_Order, Project_Date DESC)
    WHERE Is_Visible;

CREATE INDEX IF NOT EXISTS Repository_Technology_Technology_ID_IDX
    ON Repository_Technology (Technology_ID, Repository_ID);